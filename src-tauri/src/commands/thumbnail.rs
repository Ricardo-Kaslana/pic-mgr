use tauri::{State, Emitter};
use crate::AppState;
use std::sync::Mutex;
use std::collections::HashMap;

pub struct ThumbnailState {
    pub cache: Mutex<crate::scanner::thumbnail::ThumbnailCache>,
    /// Lazily-cached workspace paths keyed by workspace_id — avoids 2× DB query per thumbnail
    pub workspace_paths: Mutex<HashMap<i64, std::path::PathBuf>>,
}

/// Resolve workspace path from cache or DB. Caller must hold the DB lock.
fn get_workspace_path_cached(
    thumb_state: &ThumbnailState,
    conn: &rusqlite::Connection,
    workspace_id: i64,
) -> Result<std::path::PathBuf, String> {
    {
        let paths = thumb_state.workspace_paths.lock().map_err(|e| e.to_string())?;
        if let Some(path) = paths.get(&workspace_id) {
            return Ok(path.clone());
        }
    }
    let ws = crate::db::queries::get_workspace(conn, workspace_id)
        .map_err(|e| e.to_string())?
        .ok_or_else(|| format!("Workspace {} not found", workspace_id))?;
    let path = std::path::PathBuf::from(&ws.path);
    let mut paths = thumb_state.workspace_paths.lock().map_err(|e| e.to_string())?;
    paths.insert(workspace_id, path.clone());
    Ok(path)
}

#[tauri::command]
pub fn get_thumbnail(
    state: State<AppState>,
    thumb_state: State<ThumbnailState>,
    image_id: i64,
) -> Result<Vec<u8>, String> {
    // Fast path: thumbnail already cached on disk
    {
        let cache = thumb_state.cache.lock().map_err(|e| e.to_string())?;
        if let Some(bytes) = cache.get_bytes(image_id) {
            return Ok(bytes);
        }
    }

    // Slow path: need to generate — batch DB reads into single lock window
    let gen_result: Result<String, String> = {
        let conn = state.db.conn.lock().map_err(|e| e.to_string())?;
        let record = crate::db::queries::get_image_detail(&conn, image_id)
            .map_err(|e| e.to_string())?
            .ok_or_else(|| "Image not found".to_string())?;
        let ws_path = get_workspace_path_cached(&thumb_state, &conn, record.workspace_id)?;
        let source_path = ws_path.join(&record.relative_path);
        // Generate without holding DB lock
        drop(conn);

        let cache = thumb_state.cache.lock().map_err(|e| e.to_string())?;
        let result = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
            cache.generate(&source_path, image_id)
        }));
        match result {
            Ok(Ok(path)) => Ok(path),
            Ok(Err(e)) => Err(e),
            Err(_) => Err(format!("Failed to process image: {}", source_path.display())),
        }
    };

    // Update thumbnail_path (brief DB lock)
    if let Ok(ref path) = gen_result {
        let conn = state.db.conn.lock().map_err(|e| e.to_string())?;
        crate::db::queries::update_thumbnail_path(&conn, image_id, path)
            .map_err(|e| e.to_string())?;
    }

    // Read back generated bytes
    let cache = thumb_state.cache.lock().map_err(|e| e.to_string())?;
    cache.get_bytes(image_id).ok_or_else(|| "Failed to read generated thumbnail".to_string())
}

/// Batch thumbnail loading: single IPC call for multiple image IDs.
/// Minimizes DB lock contention by querying all records in one go.
#[derive(serde::Serialize)]
pub struct ThumbnailBatchEntry {
    pub image_id: i64,
    pub bytes: Vec<u8>,
}

#[tauri::command]
pub fn get_thumbnails_batch(
    state: State<AppState>,
    thumb_state: State<ThumbnailState>,
    image_ids: Vec<i64>,
) -> Result<Vec<ThumbnailBatchEntry>, String> {
    let mut results = Vec::with_capacity(image_ids.len());
    let mut miss_ids: Vec<i64> = Vec::new();

    // Phase 1: Collect cache hits, gather miss IDs
    {
        let cache = thumb_state.cache.lock().map_err(|e| e.to_string())?;
        for &id in &image_ids {
            if let Some(bytes) = cache.get_bytes(id) {
                results.push(ThumbnailBatchEntry { image_id: id, bytes });
            } else {
                miss_ids.push(id);
            }
        }
    }

    if miss_ids.is_empty() {
        return Ok(results);
    }

    // Phase 2: Batch-fetch image records (single DB lock), generate thumbnails
    let miss_records: Vec<(i64, i64, String)> = {
        let conn = state.db.conn.lock().map_err(|e| e.to_string())?;
        let mut stmt = conn.prepare(
            "SELECT id, workspace_id, relative_path FROM images WHERE id = ?1"
        ).map_err(|e| e.to_string())?;

        let mut records = Vec::with_capacity(miss_ids.len());
        for &id in &miss_ids {
            if let Ok(row) = stmt.query_row(rusqlite::params![id], |row| {
                Ok((row.get::<_, i64>(0)?, row.get::<_, i64>(1)?, row.get::<_, String>(2)?))
            }) {
                records.push(row);
            }
        }
        records
    };

    if miss_records.is_empty() {
        return Ok(results);
    }

    // Resolve workspace path once (all records in this workspace)
    let workspace_id = miss_records[0].1;
    let ws_path = {
        let conn = state.db.conn.lock().map_err(|e| e.to_string())?;
        get_workspace_path_cached(&thumb_state, &conn, workspace_id)?
    };

    // Generate thumbnails without DB lock
    let mut thumb_paths: Vec<(i64, String)> = Vec::with_capacity(miss_records.len());
    {
        let cache = thumb_state.cache.lock().map_err(|e| e.to_string())?;
        for &(id, _, ref rel_path) in &miss_records {
            let source_path = ws_path.join(rel_path);
            let result = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
                cache.generate(&source_path, id)
            }));
            if let Ok(Ok(p)) = result {
                if let Some(bytes) = cache.get_bytes(id) {
                    results.push(ThumbnailBatchEntry { image_id: id, bytes });
                }
                thumb_paths.push((id, p));
            }
        }
    }

    // Batch-update thumbnail_paths (single brief DB lock)
    if !thumb_paths.is_empty() {
        let conn = state.db.conn.lock().map_err(|e| e.to_string())?;
        for (id, path) in &thumb_paths {
            crate::db::queries::update_thumbnail_path(&conn, *id, path).ok();
        }
    }

    Ok(results)
}

#[tauri::command]
pub fn generate_thumbnail(
    state: State<AppState>,
    thumb_state: State<ThumbnailState>,
    image_id: i64,
) -> Result<(), String> {
    let gen_result: Result<String, String> = {
        let conn = state.db.conn.lock().map_err(|e| e.to_string())?;
        let record = crate::db::queries::get_image_detail(&conn, image_id)
            .map_err(|e| e.to_string())?
            .ok_or_else(|| "Image not found".to_string())?;
        let ws = get_workspace_path_cached(&thumb_state, &conn, record.workspace_id)?;
        let source_path = ws.join(&record.relative_path);
        drop(conn);

        let cache = thumb_state.cache.lock().map_err(|e| e.to_string())?;
        let result = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
            cache.generate(&source_path, image_id)
        }));
        match result {
            Ok(Ok(path)) => Ok(path),
            Ok(Err(e)) => Err(e),
            Err(_) => Err(format!("Failed to process image: {}", source_path.display())),
        }
    };

    if let Ok(ref path) = gen_result {
        let conn = state.db.conn.lock().map_err(|e| e.to_string())?;
        crate::db::queries::update_thumbnail_path(&conn, image_id, path)
            .map_err(|e| e.to_string())?;
    }
    Ok(())
}

/// Background thumbnail generation after scan: generates thumbnails for all image_ids,
/// emitting progress events. Skips files whose thumbnails already exist on disk.
#[tauri::command]
pub fn generate_thumbnails_batch(
    state: State<AppState>,
    thumb_state: State<ThumbnailState>,
    app: tauri::AppHandle,
    image_ids: Vec<i64>,
) -> Result<(), String> {
    if image_ids.is_empty() {
        return Ok(());
    }

    // Batch-fetch image record info with single DB lock
    let records: Vec<(i64, String)> = {
        let conn = state.db.conn.lock().map_err(|e| e.to_string())?;

        // Determine workspace path (use first image's workspace)
        let ws_id = {
            let mut stmt = conn.prepare(
                "SELECT workspace_id FROM images WHERE id = ?1"
            ).map_err(|e| e.to_string())?;
            stmt.query_row(rusqlite::params![image_ids[0]], |row| row.get::<_, i64>(0))
                .map_err(|e| e.to_string())?
        };
        let ws_path = get_workspace_path_cached(&thumb_state, &conn, ws_id)?;

        let mut stmt = conn.prepare(
            "SELECT id, relative_path FROM images WHERE id = ?1"
        ).map_err(|e| e.to_string())?;

        let mut recs = Vec::with_capacity(image_ids.len());
        for &id in &image_ids {
            if let Ok(row) = stmt.query_row(rusqlite::params![id], |row| {
                Ok((row.get::<_, i64>(0)?, row.get::<_, String>(1)?))
            }) {
                // Skip if thumbnail already exists on disk
                let thumb_path = thumb_state.cache.lock().map_err(|e| e.to_string())?
                    .cache_path(id);
                if thumb_path.exists() {
                    continue;
                }
                recs.push((id, ws_path.join(&row.1).to_string_lossy().to_string()));
            }
        }
        recs
    };

    if records.is_empty() {
        return Ok(());
    }

    let total = records.len() as i64;
    let mut generated: i64 = 0;
    let mut failed: i64 = 0;
    let flush_interval = 10;

    for chunk in records.chunks(flush_interval) {
        let mut paths_to_update: Vec<(i64, String)> = Vec::with_capacity(chunk.len());

        {
            let cache = thumb_state.cache.lock().map_err(|e| e.to_string())?;
            for &(id, ref src_path) in chunk {
                let result = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
                    cache.generate(std::path::Path::new(src_path), id)
                }));
                match result {
                    Ok(Ok(thumb_path)) => {
                        generated += 1;
                        paths_to_update.push((id, thumb_path));
                    }
                    _ => { failed += 1; }
                }
            }
        }

        // Batch-update thumbnail_paths
        if !paths_to_update.is_empty() {
            let conn = state.db.conn.lock().map_err(|e| e.to_string())?;
            for (id, path) in &paths_to_update {
                crate::db::queries::update_thumbnail_path(&conn, *id, path).ok();
            }
        }

        app.emit("thumbnail-progress", crate::models::ThumbnailProgress {
            total,
            generated,
            failed,
            finished: generated + failed >= total,
        }).map_err(|e| e.to_string())?;
    }

    Ok(())
}
